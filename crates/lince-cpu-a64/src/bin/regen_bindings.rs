//! Regenerates `src/ffi/bindings.rs` from `cpp/include/lince-cpu-a64.h` with bindgen (ADR-0030:
//! Rust declarations are generated from the header and checked in).
//!
//! - `cargo run -p lince-cpu-a64 --features regen --bin regen_bindings` rewrites the file.
//! - `… -- --check` fails if the checked-in file differs, which CI runs.
#![allow(
    clippy::print_stderr,
    reason = "command-line tool: results go to the terminal"
)]

use std::path::Path;
use std::process::ExitCode;

const HEADER: &str = "cpp/include/lince-cpu-a64.h";
const OUTPUT: &str = "src/ffi/bindings.rs";
const PREAMBLE: &str = "// SPDX-FileCopyrightText: 2026 Lince contributors
// SPDX-License-Identifier: GPL-3.0-or-later

//! Generated by `cargo run -p lince-cpu-a64 --features regen --bin regen_bindings` from
//! `cpp/include/lince-cpu-a64.h`. Do not edit by hand (STRUCT-14).
#![allow(
    non_camel_case_types,
    missing_docs,
    unreachable_pub,
    clippy::all,
    clippy::pedantic,
    reason = \"generated by bindgen\"
)]

";

fn main() -> ExitCode {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let check = std::env::args().nth(1).as_deref() == Some("--check");
    let generated = match bindgen::Builder::default()
        .header(root.join(HEADER).to_string_lossy())
        .allowlist_function("lca_.*")
        .allowlist_type("lca_.*")
        .allowlist_var("LCA_.*")
        .layout_tests(true)
        .use_core()
        // Format like `cargo fmt` would, so formatting the crate does not make the file stale.
        .formatter(bindgen::Formatter::Rustfmt)
        .generate()
    {
        // rustfmt run by bindgen may emit CRLF on Windows; the repository stores LF.
        Ok(b) => format!("{PREAMBLE}{b}").replace("\r\n", "\n"),
        Err(e) => {
            eprintln!("bindgen failed: {e}");
            return ExitCode::FAILURE;
        }
    };
    let path = root.join(OUTPUT);
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if current.replace("\r\n", "\n") == generated {
            eprintln!("{OUTPUT} matches {HEADER}");
            ExitCode::SUCCESS
        } else {
            eprintln!(
                "{OUTPUT} is stale; run `cargo run -p lince-cpu-a64 --features regen --bin regen_bindings`"
            );
            ExitCode::FAILURE
        }
    } else if let Err(e) = std::fs::write(&path, generated) {
        eprintln!("write {OUTPUT}: {e}");
        ExitCode::FAILURE
    } else {
        eprintln!("wrote {OUTPUT}");
        ExitCode::SUCCESS
    }
}
